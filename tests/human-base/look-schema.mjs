// Build sections/guitar-goblin/human-base/look-schema.js: the whitelist look-parse.js reads looks from other people
// against, generated from the creator's own lists so the two cannot drift.
//   the species and every key a link may carry for each, with its values and default:
//     characters/looks-page.js  ORDER, PEOPLE, optionsFor(species), defaultsOf(species)
//       optionsFor -> { key: { items: [{ key }], multi? } | { min, max } }, defaultsOf -> { key: value }
//   the body and face controls and the people they start from: human-base/controls.js  CONTROLS, CONTROL_DEFAULTS
// Usage: node --import ./tests/human-base/three-hook.mjs tests/human-base/look-schema.mjs          write it
//        node --import ./tests/human-base/three-hook.mjs tests/human-base/look-schema.mjs --check  exit 1 if it differs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const GG = process.env.HB_GG || join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'sections', 'guitar-goblin'), OUT = join(GG, 'human-base', 'look-schema.js');
const imp = (p) => import(pathToFileURL(join(GG, p)).href);
const { ORDER, PEOPLE, optionsFor, defaultsOf } = await imp('characters/looks-page.js');
const { CONTROLS, CONTROL_DEFAULTS } = await imp('human-base/controls.js');

const NAME = /^[a-z][A-Za-z0-9]{0,31}$/, VAL = /^[A-Za-z0-9_\-]{1,40}$/;   // (a value never holds '.', which joins a multi choice)
const fail = (m) => { console.error('look-schema: ' + m); process.exit(1); };
const S = { version: 1, maxLength: 2048, speciesOrder: [], species: {}, people: {}, controlOrder: [], controls: {} };
for (const sp of ORDER) {
  if (!NAME.test(sp)) fail(`species key ${sp}`);
  const opts = optionsFor(sp), defs = defaultsOf(sp), keys = {}, order = [];
  for (const [k, o] of Object.entries(opts)) {
    if (k === 'species') continue;
    if (!NAME.test(k)) fail(`${sp}: key ${k}`);
    let e;
    if (Array.isArray(o.items)) {
      const items = o.items.map((it) => it.key);
      for (const v of items) if (!VAL.test(v)) fail(`${sp}.${k}: value ${v}`);
      e = { items }; if (o.multi) e.multi = true;
      const d = String(defs[k] ?? items[0]);
      if (o.multi) { const ok = d.split('.').filter((v) => items.includes(v)); e.def = items.filter((v) => ok.includes(v)).join('.'); }
      else e.def = items.includes(d) ? d : items[0];
    } else if (typeof o.min === 'number' && typeof o.max === 'number') {
      e = { range: [o.min, o.max], def: Math.min(o.max, Math.max(o.min, Number(defs[k] ?? o.min))) };
    } else fail(`${sp}.${k}: neither a list nor a range`);
    keys[k] = e; order.push(k);
  }
  if (!keys.people) fail(`${sp}: no people`);
  S.speciesOrder.push(sp); S.species[sp] = { order, keys };
}
for (const c of [...CONTROLS.build, ...CONTROLS.head]) {
  if (!NAME.test(c.key)) fail(`control ${c.key}`);
  S.controlOrder.push(c.key); S.controls[c.key] = { min: c.min, max: c.max, def: CONTROL_DEFAULTS[c.key] };
}
for (const [name, p] of Object.entries(PEOPLE)) {
  if (!NAME.test(name)) fail(`person ${name}`);
  const c = {}; for (const k of S.controlOrder) if (p.controls && Object.prototype.hasOwnProperty.call(p.controls, k)) c[k] = p.controls[k];
  S.people[name] = c;
}
const text = `/* Generated by tests/human-base/look-schema.mjs from the character creator's own lists (characters/looks-page.js
   and human-base/controls.js); do not edit by hand. The whitelist look-parse.js reads a look against. */
(function (root, data) {
  if (typeof module === 'object' && module.exports) module.exports = data;
  else root.HBLookSchema = data;
})(typeof globalThis !== 'undefined' ? globalThis : this, ${JSON.stringify(S)});
`;
if (process.argv.includes('--check')) {
  let old = ''; try { old = readFileSync(OUT, 'utf8'); } catch (e) {}
  if (old !== text) { console.error('look-schema.js does not match the creator\'s lists: run tests/human-base/look-schema.mjs'); process.exit(1); }
  console.log('look-schema.js matches the creator\'s lists');
} else { writeFileSync(OUT, text); console.log(`look-schema.js: ${text.length} bytes, ${S.speciesOrder.length} species, ${S.controlOrder.length} controls`); }
